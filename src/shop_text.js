/** 모자란 재화 → 안내 한 줄 ('금화가 부족합니다.' · '금화와 뿔피리가 부족합니다.') */
export function shortText(short) {
  const names = short.map((k) => SHOP_TEXT[k]).filter(Boolean);
  if (!names.length) return '';
  const last = names[names.length - 1];
  const josa = /[가-힣]$/.test(last) && (last.charCodeAt(last.length - 1) - 0xac00) % 28 ? '이' : '가'; // 받침이 있으면 '이'
  const join = names.length === 1 ? last : `${names.slice(0, -1).map((n, i) => `${n}${(n.charCodeAt(n.length - 1) - 0xac00) % 28 ? '과' : '와'}`).join(' ')} ${last}`;
  return `${join}${josa} 부족합니다.`;
}

/** 남은 시간 → '3시간 12분' · '12분' · '1분 미만' */
export function leftText(ms) {
  const m = Math.max(0, Math.floor(ms / 60000)), h = Math.floor(m / 60), r = m % 60;
  if (!m) return '1분 미만';
  return h ? `${h}시간${r ? ` ${r}분` : ''}` : `${r}분`;
}
