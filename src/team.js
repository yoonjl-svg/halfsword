/** 자리 번호 → 기본 편 (짝수 → 0 편, 홀수 → 1 편) */
export const teamOfIndex = (index) => index % 2;

/**
 * 같은 편인가 (자기 자신 포함). 편이 적히지 않은 가짜 싸움꾼(시험 도구)은 같은 몸일 때만 같은 편 —
 *  예전 판정 `a === b` 와 같다. 1:1 에서는 편 = 자리 번호라 이 판정이 `a === b` 와 늘 같은 답이다
 */
export function sameSide(a, b) {
  if (!a || !b) return false;
  return a === b || (a.team != null && a.team === b.team);
}

/**
 * 싸움꾼 짝 열쇠 (combat.js 칼 겨루기 짝마다 — 11/20 전엔 앞 자리 × 4 + 뒤 자리): 차례 있는 자리 짝 (i, j) → 정수 하나 (칸토어 짝 — 자리 수 제한 없이 서로 다름)
 *  짝의 차례(맵에 들어온 차례)는 열쇠 값과 상관없다 — 1:1 · 2:2 의 겨룸 차례 · 소리 접촉은 예전 그대로
 */
export const pairKey = (i, j) => ((i + j) * (i + j + 1)) / 2 + j;
